namespace Content.Client._WG.Options.UI.Tabs;

/// <summary>The Extra tab: every fork setting a player can change, on the shared Apply row.</summary>
[GenerateTypedNameReferences]
public sealed partial class WolfgateExtraTab : Control
{
    private CameraModesSystem? _cameraModes;
    private readonly CameraModeOption _cameraMode;

    public WolfgateExtraTab()
    {
        RobustXamlLoader.Load(this);

        var styles = WolfgateSkins.All
            .Select(skin => new OptionDropDownCVar<string>.ValueOption(skin.Id, Loc.GetString(skin.Name)))
            .ToList();
        Control.AddOptionDropDown(WolfgateCVars.UiStyle, DropDownWolfgateStyle, styles);
        Control.AddOptionCheckBox(WolfgateCVars.WindowPopout, WindowPopoutCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.CockpitAutoEnter, CockpitAutoEnterCheckBox);
        Control.AddOptionCheckBox(WGCameraCVars.DefaultNorth, DefaultNorthCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.RadarSmartTags, RadarSmartTagsCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.RadarIconsOnly, RadarIconsOnlyCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.RadarHoverReveal, RadarHoverRevealCheckBox);
        Control.AddOptionCheckBox(WGNewbieCVars.ShowTag, ShowNewbieTagCheckBox);

        Control.AddOptionCheckBox(HeatHazeCVars.Enabled, HeatHazeCheckBox);
        Control.AddOptionPercentSlider(HeatHazeCVars.Strength, HeatHazeStrengthSlider, 0, 2);
        Control.AddOptionCheckBox(ShockwaveCVars.Enabled, ShockwaveCheckBox);
        Control.AddOptionPercentSlider(ShockwaveCVars.Strength, ShockwaveStrengthSlider, 0, 2);

        _cameraMode = Control.AddOption(new CameraModeOption(Control, IoCManager.Resolve<IConfigurationManager>(),
            (CameraMode.Perspective, CameraPerspectiveCheckBox), (CameraMode.Isometric, CameraIsometricCheckBox),
            (CameraMode.FirstPerson, CameraFirstPersonCheckBox)));
        Control.AddOptionSlider(CameraModeCVars.FieldOfView, CameraFovSlider, 60, 110);
        Control.AddOptionCheckBox(CameraModeCVars.Retro, CameraRetroCheckBox);
        Control.AddOptionCheckBox(CameraModeCVars.Billboards, CameraBillboardsCheckBox);
        Control.AddOption(new OptionSliderFloatCVar(Control, IoCManager.Resolve<IConfigurationManager>(),
            CameraModeCVars.LookSensitivity, CameraLookSensitivitySlider, 1f, 10f, 1f, (_, value) => $"{value:0.0}"));

        Control.AddOptionCheckBox(WolfmedCVars.CritHeartbeat, CritHeartbeatCheckBox);
        Control.AddOptionCheckBox(WolfmedCVars.DyingEffects, DyingEffectsCheckBox);
        Control.AddOptionCheckBox(WolfmedCVars.SyntheticHud, SyntheticHudCheckBox);
        Control.AddOptionPercentSlider(WolfmedCVars.SyntheticHudScale, SyntheticHudScaleSlider, 0.6f, 2.5f);

        Control.AddOptionPercentSlider(InternetSoundCVars.Volume, InternetSoundVolumeSlider);
        Control.AddOptionPercentSlider(JukeboxVolumeCVars.Volume, JukeboxVolumeSlider);
        Control.AddOptionCheckBox(SoundtrackMuteCVars.Enabled, SoundtrackMuteCheckBox);

        // The one setting of the Delta-V tab this one replaces.
        Control.AddOptionCheckBox(DCCVars.NoVisionFilters, DisableFiltersCheckBox);

        Control.Initialize();
    }

    /// <summary>Shows the unsaved graphics toggles in game while the window is open.</summary>
    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        _cameraModes ??= IoCManager.Resolve<IEntitySystemManager>().GetEntitySystemOrNull<CameraModesSystem>();
        _cameraModes?.SetPreview(_cameraMode.Selected, CameraBillboardsCheckBox.Pressed, CameraRetroCheckBox.Pressed,
            (int) CameraFovSlider.Slider.Value);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _cameraModes?.ClearPreview();
    }
}
